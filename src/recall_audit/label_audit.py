"""Label audit: are some of the recall model's "misses" real recalls the exact-match label missed?

Read-only. Reads Justine's test predictions (data/processed/predictions_stg.parquet) and
stg.recalls; changes no labels or model code. For every test row it asks, besides the exact
label (recall for the same make + model + model_year + component within 6 months of month end):

  variant     same make, year and part, model name is a variant (one is a prefix of the other,
              e.g. GRANDCHEROKEE / GRANDCHEROKEE4XE / GRANDCHEROKEEL)
  adj_year    same make, model and part, model year +-1
  late        exact match, but 6-12 months after month end (just past the horizon)
  other_part  same make, model and year, a different part

and reports precision@20 (LightGBM and the complaint-count baseline) and the base rate under
each looser label, added one at a time on top of the exact label.

    python -m src.recall_audit.label_audit          # writes reports/label_audit.md + .csv
"""

from __future__ import annotations

import argparse
from pathlib import Path

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
PREDICTIONS = ROOT / "data" / "processed" / "predictions_stg.parquet"
DB = ROOT / "data" / "nhtsa.duckdb"
REPORT_MD = ROOT / "reports" / "label_audit.md"
REPORT_CSV = ROOT / "reports" / "label_audit_stg.csv"
TOP = 20
MARKER = "<!-- tables below are generated by src/recall_audit/label_audit.py -->"
MIN_PREFIX = 3  # shortest model name allowed to count as a prefix of a variant

LOOSER = ["variant", "adj_year", "late", "other_part"]
DESCRIBE = {
    "exact": "exact label (Justine's y_6m)",
    "variant": "+ model-name variant (4xe, L, Hybrid, ...)",
    "adj_year": "+ model year +-1",
    "late": "+ recall 6-12 months out",
    "other_part": "+ same car, different part",
}


def flag_sql(predictions: Path) -> str:
    """One row per test row: exact label plus a boolean per looser match."""
    p = predictions.as_posix()
    window = "r.recall_date > t.as_of and r.recall_date <= t.as_of + interval 6 month"
    return f"""
    with t as (
        select make, model, model_year, component, month::date as month, y, baseline, score,
               last_day(month::date) as as_of
        from read_parquet('{p}') where split = 'test'
    ),
    r as (
        select distinct make, model, model_year, component, recall_date
        from db.stg.recalls where recall_date is not null and model_year is not null
    ),
    variant as (
        select distinct t.make, t.model, t.model_year, t.component, t.month, r.model as matched
        from t join r on r.make = t.make and r.model_year = t.model_year
                     and r.component = t.component and r.model <> t.model
                     and least(length(r.model), length(t.model)) >= {MIN_PREFIX}
                     and (starts_with(r.model, t.model) or starts_with(t.model, r.model))
                     and {window}
    ),
    adj as (
        select distinct t.make, t.model, t.model_year, t.component, t.month
        from t join r on r.make = t.make and r.model = t.model and r.component = t.component
                     and abs(r.model_year - t.model_year) = 1 and {window}
    ),
    late as (
        select distinct t.make, t.model, t.model_year, t.component, t.month
        from t join r on r.make = t.make and r.model = t.model and r.model_year = t.model_year
                     and r.component = t.component
                     and r.recall_date > t.as_of + interval 6 month
                     and r.recall_date <= t.as_of + interval 12 month
    ),
    other as (
        select distinct t.make, t.model, t.model_year, t.component, t.month
        from t join r on r.make = t.make and r.model = t.model and r.model_year = t.model_year
                     and r.component <> t.component and {window}
    ),
    v as (
        select make, model, model_year, component, month, string_agg(matched, ',') as variant_models
        from variant group by all
    )
    select t.make, t.model, t.model_year, t.component, t.month, t.y as exact, t.baseline, t.score,
           v.make is not null as variant, v.variant_models,
           adj.make is not null as adj_year,
           late.make is not null as late,
           other.make is not null as other_part
    from t
    left join v using (make, model, model_year, component, month)
    left join adj using (make, model, model_year, component, month)
    left join late using (make, model, model_year, component, month)
    left join other using (make, model, model_year, component, month)
    """


def load_flags(predictions: Path = PREDICTIONS, db: Path = DB) -> pd.DataFrame:
    with duckdb.connect() as con:
        con.execute(f"attach '{db.as_posix()}' as db (read_only)")
        con.execute("set preserve_insertion_order = false")
        return con.sql(flag_sql(predictions)).df()


def top_k(df: pd.DataFrame, col: str, k: int = TOP) -> pd.DataFrame:
    # same tie handling as Justine's flags(): stable sort by month, then score descending
    return df.sort_values(["month", col], ascending=[True, False]).groupby("month").head(k)


def summarize(df: pd.DataFrame) -> pd.DataFrame:
    """Cumulative looser labels: exact, exact|variant, exact|variant|adj_year, ..."""
    tops = {"lgbm": top_k(df, "score"), "baseline": top_k(df, "baseline")}
    rows, label = [], df["exact"].astype(bool)
    labels = {"exact": label}
    for name in LOOSER:
        label = label | df[name].astype(bool)
        labels[name] = label
    for name, lab in labels.items():
        row = {"label": DESCRIBE[name], "base_rate": lab.mean()}
        for scorer, top in tops.items():
            hit = lab.loc[top.index]
            row[f"{scorer}_precision_at_20"] = hit.groupby(top["month"]).mean().mean()
            row[f"{scorer}_hits"] = int(hit.sum())
        row["lgbm_lift"] = row["lgbm_precision_at_20"] / row["base_rate"]
        rows.append(row)
    return pd.DataFrame(rows)


def miss_breakdown(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    top = top_k(df, "score")
    misses = top[~top["exact"].astype(bool)].copy()
    counts = pd.DataFrame({
        "match": LOOSER,
        "misses_matched": [int(misses[m].sum()) for m in LOOSER],
    })
    counts["share_of_misses"] = counts["misses_matched"] / len(misses)
    return counts, misses


def _pct(x: float) -> str:
    return f"{x:.1%}"


def write_report(summary: pd.DataFrame, counts: pd.DataFrame, misses: pd.DataFrame, n_top: int) -> str:
    lines = [
        "## Tables",
        "",
        f"The model's top {TOP} per month over 36 months = {n_top} flags; {len(misses)} are misses",
        "under the exact label. For each looser match, how many of those misses it would turn into",
        "hits (a miss can match more than one):",
        "",
        "| Looser match | Misses it matches | Share of misses |",
        "| --- | --- | --- |",
    ]
    for _, r in counts.iterrows():
        lines.append(f"| {DESCRIBE[r['match']].lstrip('+ ')} | {r['misses_matched']} | {_pct(r['share_of_misses'])} |")
    lines += [
        "",
        "Precision@20 if each looser match also counted (cumulative, top to bottom). The base rate",
        "is over every ranked test row, so a looser label that just makes recalls more common",
        "raises it too; lift = LightGBM precision / base rate.",
        "",
        "| Label | Base rate | LightGBM precision@20 | LightGBM hits | Baseline precision@20 | Lift |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for _, r in summary.iterrows():
        lines.append(
            f"| {r['label']} | {_pct(r['base_rate'])} | {_pct(r['lgbm_precision_at_20'])} | "
            f"{r['lgbm_hits']} | {_pct(r['baseline_precision_at_20'])} | {r['lgbm_lift']:.0f}x |"
        )
    variants = (misses[misses["variant"]]
                .assign(pair=lambda d: d["model"].astype(str) + " -> " + d["variant_models"].astype(str))
                .groupby(["make", "pair"]).size().sort_values(ascending=False).head(10))
    lines += ["", "Most common model-name variant matches among misses (flagged model -> recalled model):", ""]
    lines += [f"- {make} {pair}: {n}" for (make, pair), n in variants.items()] or ["- none"]
    examples = misses[misses[LOOSER].any(axis=1)].head(10)
    lines += ["", "Example misses that a looser match would count:", "",
              "| Month | Vehicle | Part | Matches |", "| --- | --- | --- | --- |"]
    for _, r in examples.iterrows():
        tags = ", ".join(m for m in LOOSER if r[m])
        lines.append(f"| {r['month']:%Y-%m} | {r['make']} {r['model']} {r['model_year']} | "
                     f"{r['component']} | {tags} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--predictions", type=Path, default=PREDICTIONS)
    args = parser.parse_args()
    df = load_flags(args.predictions)
    summary = summarize(df)
    counts, misses = miss_breakdown(df)
    generated = write_report(summary, counts, misses, len(top_k(df, "score")))
    # keep the hand-written findings above the marker; regenerate only the tables below it
    kept = ""
    if REPORT_MD.exists() and MARKER in REPORT_MD.read_text(encoding="utf-8"):
        kept = REPORT_MD.read_text(encoding="utf-8").split(MARKER)[0]
    REPORT_MD.write_text(kept + MARKER + "\n\n" + generated if kept else generated, encoding="utf-8")
    summary.to_csv(REPORT_CSV, index=False)
    pd.set_option("display.width", 200)
    print(summary.round(4).to_string(index=False))
    print(counts.to_string(index=False))
    print(f"wrote {REPORT_MD.relative_to(ROOT)} and {REPORT_CSV.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
